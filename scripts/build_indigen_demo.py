"""Builds the IndiGen DEMO dataset: SYNTHETIC values for demonstrating the IndiGen parts of the UI. NOT IndiGen evidence.

    python scripts/build_indigen_demo.py                       # genes currently in the gnomAD cache (+ SLC26A4, PAX8, TSHR)
    python scripts/build_indigen_demo.py --genes KCNJ10,FOXI1  # add genes

What is real and what is not:
  * variant identifiers (GRCh38 chrom:pos:ref:alt) and ClinVar VariationIDs are taken from the project's real ClinVar P/LP table, so the
    demo rows line up with the real ClinVar / gnomAD rows in the panel;
  * every allele count, allele number and frequency is GENERATED here with a pseudo-random generator seeded by (SEED, variant_id).
    They are not measured from any genome, not derived from gnomAD (gnomAD values are never read), and not obtained from CSIR-IGIB.

Deterministic: the same seed and variant always give the same numbers, independent of gene order or which genes are included.
Output: data/demo/indigen_demo/indigen_demo_v1.json.gz (outside every real-data path: never data/raw/indigen, data/processed/population,
or the gnomAD gene cache).
"""
import argparse
import gzip
import hashlib
import json
import os
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

sys.path.insert(0, os.path.abspath("."))
from src.population.indigen_demo import DEMO_LABEL, DEMO_PATH, SCHEMA_VERSION  # noqa: E402

SEED = 20261009
SIM_AN = 2000                       # simulated allele number (a fixed demo cohort size; NOT a real cohort)
PLP = Path("data/processed/population/clinvar_plp_grch38.parquet")
CACHE = Path("data/raw/gnomad/gene_cache")
ALWAYS = ["SLC26A4", "PAX8", "TSHR"]


def simulate(variant_id: str, seed: int = SEED) -> dict:
    rng = random.Random(int.from_bytes(hashlib.sha256(f"{seed}:{variant_id}".encode()).digest()[:8], "big"))
    an = SIM_AN if rng.random() > 0.05 else SIM_AN - 2 * rng.randint(1, 20)      # a few sites with simulated missing calls
    ac = 0 if rng.random() < 0.65 else min(an // 10, max(1, int(rng.paretovariate(1.6))))
    return {"demo_ac": ac, "demo_an": an, "demo_af": ac / an}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--genes", default="", help="extra comma-separated gene symbols")
    a = ap.parse_args()
    plp = pd.read_parquet(PLP, columns=["variant_id", "gene", "variation_id"]).drop_duplicates(["gene", "variant_id"])
    genes = sorted({p.stem for p in CACHE.glob("*.json")} | set(ALWAYS) | {g.strip().upper() for g in a.genes.split(",") if g.strip()})
    out_genes, n = {}, 0
    for g, sub in plp[plp.gene.isin(genes)].groupby("gene"):
        rows = []
        for vid, vcv in sorted(zip(sub.variant_id, sub.variation_id)):
            rows.append({"variant_id": vid, "clinvar_variation_id": str(vcv), **simulate(vid)})
        out_genes[g] = {"variants": rows, "demo_caf": sum(r["demo_af"] for r in rows),
                        "n_variants": len(rows), "n_variants_nonzero": sum(r["demo_ac"] > 0 for r in rows)}
        n += len(rows)
    data = {
        "schema_version": SCHEMA_VERSION,
        "provenance": {
            "synthetic": True, "label": DEMO_LABEL,
            "statement": "Synthetic demonstration data. Values were generated by a seeded pseudo-random process. They were NOT measured "
                         "from Indian genomes, NOT derived from gnomAD, and NOT obtained from CSIR-IGIB or the IndiGen programme.",
            "generator": "scripts/build_indigen_demo.py", "seed": SEED, "simulated_allele_number": SIM_AN,
            "method": "per variant: rng seeded by sha256(seed:variant_id); AN = 2000 (5% of sites 1960-1998); AC = 0 with p=0.65, "
                      "otherwise min(AN/10, floor(Pareto(alpha=1.6))); AF = AC/AN; gene demo_caf = sum of AF",
            "variant_identifiers_from": "ClinVar P/LP GRCh38 table (data/processed/population/clinvar_plp_grch38.parquet) - real identifiers only",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "must_not_be_used_for": ["disease ranking", "patient-level conclusions", "clinical reporting as evidence"],
        },
        "n_genes": len(out_genes), "n_records": n, "genes": out_genes,
    }
    DEMO_PATH.parent.mkdir(parents=True, exist_ok=True)
    with gzip.open(DEMO_PATH, "wt", encoding="utf-8") as f:
        json.dump(data, f, separators=(",", ":"))
    print(f"wrote {DEMO_PATH}: {len(out_genes)} genes, {n} synthetic records ({DEMO_PATH.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
